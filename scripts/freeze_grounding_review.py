"""Freeze only after each fresh grounding case has a reviewer and approved status."""
from datetime import datetime
import hashlib
import json
from pathlib import Path
import sys
from zoneinfo import ZoneInfo

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'src'))
from hr_navigator.evaluation.grounding_review import reviewed_cases  # noqa: E402

output = Path('evaluation/grounding_fresh_v1.jsonl')
checksum = Path('evaluation/grounding_fresh_v1.sha256')
note = Path('evaluation/grounding_fresh_v1_freeze.md')
if any(p.exists() for p in (output, checksum, note)):
    raise SystemExit('Frozen output already exists; create a new version instead')
cases = reviewed_cases('evaluation/grounding_fresh_draft_v0.1.jsonl',
                       'evaluation/grounding_fresh_review.csv',
                       'data/processed/accepted_ocr/pages.jsonl')
if len(cases) != 20:
    raise SystemExit('Expected 20 individually approved cases')
gold_path = Path('evaluation/gold_v1.jsonl')
gold_hash = Path('evaluation/gold_v1.sha256').read_text().split()[0]
if hashlib.sha256(gold_path.read_bytes()).hexdigest() != gold_hash:
    raise SystemExit('Existing frozen gold checksum mismatch')
gold_questions = {json.loads(line)['question'].strip().casefold() for line in gold_path.read_text().splitlines()}
if any(case['question'].strip().casefold() in gold_questions for case in cases):
    raise SystemExit('Reviewed question exactly duplicates the existing frozen gold set')
data = ''.join(json.dumps(case, ensure_ascii=False, sort_keys=True) + '\n' for case in cases).encode('utf-8')
sha = hashlib.sha256(data).hexdigest()
with output.open('xb') as f:
    f.write(data)
checksum.write_text(f'{sha}  {output.name}\n', encoding='utf-8')
when = datetime.now(ZoneInfo('Asia/Kolkata')).isoformat(timespec='seconds')
note.write_text(f'# Fresh grounding evaluation freeze\n\nFrozen {when}. Cases: {len(cases)}. '
                f'SHA256: `{sha}`. Reviewers are recorded per case in the JSONL. '
                'A recorded source page is not an exhaustive relevance set; '
                'legal applicability remains unverified. Do not edit this file.\n', encoding='utf-8')
print(f'Frozen {len(cases)} cases: SHA256 {sha}')
