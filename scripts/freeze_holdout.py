"""Freeze the reviewed grounding hold-out set as evaluation/grounding_holdout_v1 (run once, after review).

Each row of evaluation/grounding_holdout_review_v0.2.csv needs review_verdict 'approved' or 'rejected'
and a reviewer. Approved rows need the PDF page number and an exact quote from that corpus page;
rejected rows are left out. The checks are the same as for the fresh grounding set
(hr_navigator.evaluation.grounding_review.reviewed_cases).
"""
import argparse
import csv
from datetime import datetime
import hashlib
import json
from pathlib import Path
import sys
import tempfile
from zoneinfo import ZoneInfo

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'src'))
from hr_navigator.evaluation.grounding_review import reviewed_cases  # noqa: E402

parser = argparse.ArgumentParser()
parser.add_argument('--draft', default='evaluation/grounding_holdout_candidates_v0.2.jsonl')
parser.add_argument('--review', default='evaluation/grounding_holdout_review_v0.2.csv')
parser.add_argument('--pages', default='data/processed/accepted_ocr/pages.jsonl')
parser.add_argument('--minimum', type=int, default=15, help='Fewest approved cases worth freezing')
args = parser.parse_args()

output = Path('evaluation/grounding_holdout_v1.jsonl')
checksum = Path('evaluation/grounding_holdout_v1.sha256')
note = Path('evaluation/grounding_holdout_v1_freeze.md')
if any(p.exists() for p in (output, checksum, note)):
    raise SystemExit('grounding_holdout_v1 already exists; frozen files are never overwritten. Create v2 instead.')

draft = [json.loads(line) for line in Path(args.draft).read_text(encoding='utf-8').splitlines() if line.strip()]
with Path(args.review).open(encoding='utf-8-sig', newline='') as f:
    rows = list(csv.DictReader(f))
if sorted(r['case_id'] for r in rows) != sorted(d['case_id'] for d in draft):
    raise SystemExit('Review sheet case IDs do not match the draft')
problems = []
for row in rows:
    verdict = row['review_verdict'].strip().lower()
    if verdict not in {'approved', 'rejected'} or not row['reviewer'].strip():
        problems.append(f"{row['case_id']}: needs review_verdict approved/rejected and a reviewer")
    elif verdict == 'approved' and not row['pdf_page_number'].strip().isdigit():
        problems.append(f"{row['case_id']}: approved cases need the PDF page number")
if problems:
    raise SystemExit('Review is not complete:\n' + '\n'.join(problems))

approved = [r for r in rows if r['review_verdict'].strip().lower() == 'approved']
by_id = {d['case_id']: d for d in draft}
kept = []
for row in approved:
    case = dict(by_id[row['case_id']])
    case.pop('origin', None)
    if case['pdf_page_number'] is None:            # new drafts get their page from the review
        case['pdf_page_number'] = int(row['pdf_page_number'])
    kept.append(case)
with tempfile.TemporaryDirectory() as tmp:
    tmp_draft, tmp_review = Path(tmp, 'draft.jsonl'), Path(tmp, 'review.csv')
    tmp_draft.write_text(''.join(json.dumps(c, ensure_ascii=False) + '\n' for c in kept), encoding='utf-8')
    with tmp_review.open('w', encoding='utf-8', newline='') as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(approved)
    try:
        cases = reviewed_cases(tmp_draft, tmp_review, args.pages)
    except ValueError as exc:
        raise SystemExit(f'Review check failed: {exc}') from exc
if len(cases) < args.minimum:
    raise SystemExit(f'Only {len(cases)} approved cases; at least {args.minimum} are needed')

taken = set()
for path in ('evaluation/gold_v1.jsonl', 'evaluation/grounding_fresh_v1.jsonl'):
    if Path(path).exists():
        taken |= {json.loads(line)['question'].strip().casefold()
                  for line in Path(path).read_text(encoding='utf-8').splitlines() if line.strip()}
if any(c['question'].strip().casefold() in taken for c in cases):
    raise SystemExit('A hold-out question duplicates the gold or fresh grounding set')

data = ''.join(json.dumps(c, ensure_ascii=False, sort_keys=True) + '\n' for c in cases).encode('utf-8')
sha = hashlib.sha256(data).hexdigest()
with output.open('xb') as f:
    f.write(data)
checksum.write_text(f'{sha}  {output.name}\n', encoding='utf-8')
when = datetime.now(ZoneInfo('Asia/Kolkata')).isoformat(timespec='seconds')
rejected = sorted(r['case_id'] for r in rows if r['review_verdict'].strip().lower() == 'rejected')
note.write_text(
    f'# Grounding hold-out freeze\n\nFrozen {when}. Cases: {len(cases)} '
    f'(rejected in review: {", ".join(rejected) or "none"}). SHA256: `{sha}`. Reviewers are recorded per '
    'case. This set is for the final grounding measurement only: do not use it to tune retrieval, '
    'prompts or thresholds, and do not edit this file; create a new version instead.\n', encoding='utf-8')
print(f'Frozen {len(cases)} hold-out cases: SHA256 {sha}')
